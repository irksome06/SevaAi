/**
 * Translate a translation key to the active language with optional parameter interpolation
 * @param {string} lang - Language code (e.g. 'en', 'hi', 'bn', 'te', 'ta')
 * @param {string} key - Dictionary key
 * @param {object} params - Key-value replacements (e.g. { phone: '9876543210' })
 * @returns {string} Translated string
 */
export function getTranslation(lang, key, params = {}) {
  const activeDict = translations[lang] || translations.en;
  let text = activeDict[key] || translations.en[key] || key;

  // Interpolate parameters like {phone}, {name}, {seconds}
  Object.keys(params).forEach((paramKey) => {
    text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), params[paramKey]);
  });

  return text;
}
